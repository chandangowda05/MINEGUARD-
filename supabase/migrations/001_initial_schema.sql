-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================================================
-- TABLES
-- ============================================================================

-- Workers table
CREATE TABLE workers (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  worker_code TEXT UNIQUE NOT NULL,
  full_name TEXT NOT NULL,
  assigned_helmet_id UUID,
  mining_zone TEXT,
  status TEXT NOT NULL DEFAULT 'offline' CHECK (status IN ('safe', 'warning', 'critical', 'inactive', 'offline')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Helmets table
CREATE TABLE helmets (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  helmet_code TEXT UNIQUE NOT NULL,
  esp32_device_id TEXT,
  worker_id UUID REFERENCES workers(id) ON DELETE SET NULL,
  is_online BOOLEAN NOT NULL DEFAULT FALSE,
  last_seen TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Add FK from workers to helmets (circular ref, add after both tables)
ALTER TABLE workers ADD CONSTRAINT fk_workers_helmet
  FOREIGN KEY (assigned_helmet_id) REFERENCES helmets(id) ON DELETE SET NULL;

-- Sensor readings table (high volume)
CREATE TABLE sensor_readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  helmet_id UUID NOT NULL REFERENCES helmets(id) ON DELETE CASCADE,
  temperature FLOAT,
  humidity FLOAT,
  mq3_raw FLOAT,
  mq7_raw FLOAT,
  mq7_ppm FLOAT,
  accel_x FLOAT,
  accel_y FLOAT,
  accel_z FLOAT,
  gyro_x FLOAT,
  gyro_y FLOAT,
  gyro_z FLOAT,
  movement_status TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Worker locations table
CREATE TABLE worker_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  worker_id UUID NOT NULL REFERENCES workers(id) ON DELETE CASCADE,
  helmet_id UUID NOT NULL REFERENCES helmets(id) ON DELETE CASCADE,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  gps_valid BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Alerts table
CREATE TABLE alerts (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  worker_id UUID REFERENCES workers(id) ON DELETE SET NULL,
  helmet_id UUID REFERENCES helmets(id) ON DELETE SET NULL,
  alert_type TEXT NOT NULL CHECK (alert_type IN (
    'HIGH_TEMPERATURE', 'HIGH_HUMIDITY', 'HAZARDOUS_GAS', 'CARBON_MONOXIDE',
    'WORKER_INACTIVITY', 'POSSIBLE_FALL', 'SUDDEN_IMPACT',
    'RESTRICTED_ZONE_ENTRY', 'SAFE_ZONE_EXIT', 'EMERGENCY_SOS',
    'HELMET_OFFLINE', 'GPS_SIGNAL_LOST'
  )),
  severity TEXT NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
  description TEXT NOT NULL,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
  resolved BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Geofences table
CREATE TABLE geofences (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  name TEXT NOT NULL,
  zone_type TEXT NOT NULL CHECK (zone_type IN ('safe', 'restricted', 'danger')),
  geometry JSONB NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Geofence events table
CREATE TABLE geofence_events (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  worker_id UUID NOT NULL REFERENCES workers(id) ON DELETE CASCADE,
  geofence_id UUID NOT NULL REFERENCES geofences(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL CHECK (event_type IN ('enter', 'exit')),
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Worker activity table
CREATE TABLE worker_activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  worker_id UUID NOT NULL REFERENCES workers(id) ON DELETE CASCADE,
  helmet_id UUID NOT NULL REFERENCES helmets(id) ON DELETE CASCADE,
  activity_status TEXT NOT NULL,
  inactivity_duration INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- System settings table
CREATE TABLE system_settings (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  setting_key TEXT UNIQUE NOT NULL,
  setting_value JSONB NOT NULL DEFAULT '{}',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

