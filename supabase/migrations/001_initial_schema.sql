-- Update helmets.last_seen when a new sensor_reading is inserted
CREATE OR REPLACE FUNCTION update_helmet_last_seen()
RETURNS TRIGGER AS $$
BEGIN
  UPDATE helmets SET last_seen = NEW.created_at, is_online = TRUE WHERE id = NEW.helmet_id;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER trg_update_helmet_last_seen
AFTER INSERT ON sensor_readings
FOR EACH ROW EXECUTE FUNCTION update_helmet_last_seen();

